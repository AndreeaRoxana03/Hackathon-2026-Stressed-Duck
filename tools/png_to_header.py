#!/usr/bin/env python3
"""Resize a folder of PNG frames and embed them as PROGMEM byte arrays.

Usage:
    python tools/png_to_header.py <frames_dir> <output_header> <array_prefix> [width] [height]

Example:
    python tools/png_to_header.py src/frames/happyDuck src/generated/duck_happy_frames.h duck_happy 134 100
"""
import io
import sys
from pathlib import Path

from PIL import Image

DEFAULT_WIDTH = 134
DEFAULT_HEIGHT = 100


def main() -> None:
    if len(sys.argv) < 4:
        print(__doc__)
        sys.exit(1)

    frames_dir = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    prefix = sys.argv[3]
    width = int(sys.argv[4]) if len(sys.argv) > 4 else DEFAULT_WIDTH
    height = int(sys.argv[5]) if len(sys.argv) > 5 else DEFAULT_HEIGHT

    pngs = sorted(frames_dir.glob("frame_*.png"))
    if not pngs:
        raise SystemExit(f"No frame_*.png files found in {frames_dir}")

    lines = [
        "#pragma once",
        '#include "DuckAnimation.h"',
        "// Auto-generated by tools/png_to_header.py — do not edit by hand.",
        "",
    ]
    for i, png in enumerate(pngs):
        frame = Image.open(png).convert("RGBA").resize((width, height), Image.LANCZOS)
        buffer = io.BytesIO()
        frame.save(buffer, format="PNG", optimize=True)
        data = buffer.getvalue()
        byte_str = ",".join(str(b) for b in data)
        lines.append(f"static const uint8_t {prefix}_frame_{i:02d}[] PROGMEM = {{{byte_str}}};")

    lines.append("")
    lines.append(f"static const DuckFrame {prefix}_frames[] = {{")
    for i in range(len(pngs)):
        lines.append(f"    {{ {prefix}_frame_{i:02d}, sizeof({prefix}_frame_{i:02d}) }},")
    lines.append("};")
    lines.append(f"static const size_t {prefix}_frame_count = {len(pngs)};")
    lines.append(f"static const int16_t {prefix}_frame_width = {width};")
    lines.append(f"static const int16_t {prefix}_frame_height = {height};")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines))
    print(f"Wrote {len(pngs)} frames ({width}x{height}) to {out_path}")


if __name__ == "__main__":
    main()
